# DatasetFilter evaluates lambda strings; embed the frozenset literal so it is
# self-contained in the filters.py eval namespace.
_TASKSET_LITERAL = repr(set(MIMICDROID_LIKE_TASKS))
MIMICDROID_FILTER = DatasetFilter(filter_lambdas=[
    f"lambda row: row.get('task') in {_TASKSET_LITERAL}"
])

def main():
    p = argparse.ArgumentParser()
    p.add_argument('--local-dir', required=True)
    p.add_argument('--workers', type=int, default=128)
    p.add_argument('--dry-run', action='store_true', help='Only resolve+count matching episodes; no download.')
    a = p.parse_args()
    load_env()
    if a.dry_run:
        paths = S3EpisodeResolver._get_filtered_paths(MIMICDROID_FILTER)
        logging.info('DRY RUN: %d episodes matched (with non-empty zarr path).', len(paths))
        return
    S3EpisodeResolver.sync_from_filters(
        bucket_name='rldb', filters=MIMICDROID_FILTER,
        local_dir=Path(a.local_dir), numworkers=a.workers,
    )

if __name__ == '__main__':
    main()
